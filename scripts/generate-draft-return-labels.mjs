import fs from "node:fs";

const dataPath = "app/template-document-type-labels.data.ts";
const src = fs.readFileSync(dataPath, "utf8");

function extractPack(name) {
  const re = new RegExp(
    `export const ${name}: Record<string, DocumentTypeLabelOverrides> = \\{([\\s\\S]*?)\\n\\};`,
  );
  const m = src.match(re);
  if (!m) throw new Error(`pack ${name} not found`);
  const body = m[1];
  const langs = [...body.matchAll(/\n  "([^"]+)": \{([\s\S]*?)\n  \}/g)];
  const out = {};
  for (const [, lang, fields] of langs) {
    const get = (key) => {
      const fm = fields.match(new RegExp(`${key}: "((?:\\\\.|[^"\\\\])*)"`));
      return fm ? fm[1].replace(/\\"/g, '"') : "";
    };
    out[lang] = {
      documentTitle: get("documentTitle"),
      orderNumber: get("orderNumber"),
      date: get("date"),
      reference: get("reference"),
      totalLabel: get("totalLabel"),
      itemsInTotalLabel: get("itemsInTotalLabel"),
      notes: get("notes"),
      terms: get("terms"),
    };
  }
  return out;
}

