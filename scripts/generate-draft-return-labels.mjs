function resolve(map, lang) {
  if (map[lang]) return map[lang];
  const base = lang.split("-")[0];
  if (map[base]) return map[base];
  const alias = ALIASES[lang] || ALIASES[base];
  if (alias && map[alias]) return map[alias];
  return map.en;
}

function escape(str) {
  return String(str).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function emitPack(name, map) {
  const langs = Object.keys(packing);
  let out = `\nexport const ${name}: Record<string, DocumentTypeLabelOverrides> = {\n`;
  for (const lang of langs) {
    const row = resolve(map, lang);
    out += `  "${lang}": {\n`;
    out += `    documentTitle: "${escape(row.documentTitle)}",\n`;
    out += `    orderNumber: "${escape(row.orderNumber)}",\n`;
    out += `    date: "${escape(row.date)}",\n`;
    out += `    reference: "${escape(row.reference)}",\n`;
    out += `    totalLabel: "${escape(row.totalLabel)}",\n`;
    out += `    itemsInTotalLabel: "${escape(row.itemsInTotalLabel)}",\n`;
    out += `    notes: "${escape(row.notes)}",\n`;
    out += `    terms: "${escape(row.terms)}",\n`;
    out += `  },\n`;
  }
  out += `};\n`;
  return out;
}

